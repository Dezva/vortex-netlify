create table if not exists public.vortex_entradas (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  telefono text not null,
  tipo text not null check (tipo in ('anticipada','listado')),
  precio integer not null check (precio in (30000,50000)),
  estado_pago text not null default 'pendiente'
    check (estado_pago in ('pendiente','pagado','cancelado')),
  estado_entrada text not null default 'bloqueada'
    check (estado_entrada in ('bloqueada','disponible','utilizada')),
  creado_en timestamptz not null default now(),
  pagado_en timestamptz,
  utilizado_en timestamptz
);
create index if not exists vortex_entradas_creado_idx on public.vortex_entradas (id desc);
create index if not exists vortex_entradas_pago_idx on public.vortex_entradas (estado_pago);
create index if not exists vortex_entradas_acceso_idx on public.vortex_entradas (estado_entrada);

-- No dar lectura/escritura de las entradas a usuarios públicos.
alter table public.vortex_entradas enable row level security;
revoke all on table public.vortex_entradas from public, anon, authenticated;
grant select,insert,update on table public.vortex_entradas to service_role;
grant usage, select on sequence public.vortex_entradas_id_seq to service_role;

-- Ventana de conteo para reducir los abusos de registro e intentos de login.
create table if not exists public.vortex_limites (
  categoria text not null,
  clave text not null,
  ventana bigint not null,
  contador integer not null default 0,
  primary key(categoria,clave,ventana)
);
alter table public.vortex_limites enable row level security;
revoke all on table public.vortex_limites from public, anon, authenticated;
grant select,insert,update,delete on table public.vortex_limites to service_role;

create or replace function public.vortex_limite_por_ip(
  p_clave text, p_categoria text, p_max integer, p_segundos integer
) returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_ventana bigint;
  v_result integer;
begin
  if length(p_clave)<>64 or p_categoria not in ('registro','login')
     or p_max < 1 or p_max > 30 or p_segundos not in (600,900) then
     return false;
  end if;
  v_ventana := floor(extract(epoch from now()) / p_segundos)::bigint;
  insert into public.vortex_limites(categoria,clave,ventana,contador)
    values(p_categoria,p_clave,v_ventana,1)
  on conflict(categoria,clave,ventana)
    do update set contador=public.vortex_limites.contador+1
      where public.vortex_limites.contador < p_max
  returning contador into v_result;
  return v_result is not null;
end;
$$;

-- La base de datos determina el precio. Nadie lo puede cambiar desde el navegador.
create or replace function public.vortex_registrar(
  p_nombre text, p_telefono text, p_tipo text
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_nombre text := btrim(p_nombre);
  v_precio integer;
  v_codigo text;
  v_cierre timestamptz := timestamp '2026-10-17 21:00:00' at time zone 'America/Asuncion';
  v_evento timestamptz := timestamp '2026-10-30 21:30:00' at time zone 'America/Asuncion';
begin
  if now() >= v_evento then raise exception 'EVENTO_CERRADO'; end if;
  if p_tipo not in ('anticipada','listado') or
     length(v_nombre) < 3 or length(v_nombre)>80 or
     length(p_telefono)<6 or length(p_telefono)>19 or
     p_telefono !~ '^[+]?[0-9]+$' then
    raise exception 'DATOS_INVALIDOS';
  end if;
  if p_tipo='anticipada' and now()>=v_cierre then raise exception 'ANTICIPADA_CERRADA'; end if;
  v_precio := case when p_tipo='anticipada' then 30000 else 50000 end;
  v_codigo := 'VX-H26-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,20));
  insert into public.vortex_entradas(codigo,nombre,telefono,tipo,precio)
    values(v_codigo,v_nombre,p_telefono,p_tipo,v_precio);
  return jsonb_build_object('codigo',v_codigo,'precio',v_precio);
end;
$$;

-- Bloqueo de fila: dos guardias no pueden marcar simultáneamente la misma entrada.
create or replace function public.vortex_cambiar_estado(
  p_codigo text, p_accion text
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_entrada public.vortex_entradas%rowtype;
begin
  select * into v_entrada from public.vortex_entradas
  where codigo=p_codigo for update;
  if not found then raise exception 'NO_EXISTE'; end if;
  if p_accion='pay' then
    if v_entrada.estado_pago<>'pendiente' then raise exception 'ESTADO_INVALIDO'; end if;
    update public.vortex_entradas set estado_pago='pagado',
      estado_entrada='disponible',pagado_en=now()
    where id=v_entrada.id;
  elsif p_accion='use' then
    if v_entrada.estado_pago<>'pagado' or v_entrada.estado_entrada<>'disponible' then
      raise exception 'ESTADO_INVALIDO';
    end if;
    update public.vortex_entradas set estado_entrada='utilizada',utilizado_en=now()
    where id=v_entrada.id;
  elsif p_accion='cancel' then
    if v_entrada.estado_pago='cancelado' or v_entrada.estado_entrada='utilizada' then
      raise exception 'ESTADO_INVALIDO';
    end if;
    update public.vortex_entradas set estado_pago='cancelado',
      estado_entrada='bloqueada' where id=v_entrada.id;
  else
    raise exception 'ESTADO_INVALIDO';
  end if;
  return jsonb_build_object('codigo',p_codigo,'accion',p_accion,'ok',true);
end;
$$;

create or replace function public.vortex_estadisticas()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'total',count(*),
    'pagadas',count(*) filter (where estado_pago='pagado'),
    'usadas',count(*) filter (where estado_entrada='utilizada'),
    'recaudado',coalesce(sum(precio) filter (where estado_pago='pagado'),0)
  ) from public.vortex_entradas;
$$;

